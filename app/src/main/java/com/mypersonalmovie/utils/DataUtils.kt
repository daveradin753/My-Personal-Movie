package com.mypersonalmovie.utils

import com.mypersonalmovie.data.local.entity.MovieEntity
import com.mypersonalmovie.domain.model.MovieModel

fun MovieModel.toEntity(): MovieEntity {
    return MovieEntity(
        id = id ?: 0,
        adult = adult,
        backdropPath = backdropPath,
        originalLanguage = originalLanguage,
        originalTitle = originalTitle,
        overview = overview,
        popularity = popularity,
        posterPath = posterPath,
        releaseDate = releaseDate,
        title = title,
        video = video,
        voteAverage = voteAverage,
        voteCount = voteCount
    )
}

fun MovieEntity.toDomainModel(): MovieModel {
    return MovieModel(
        id = id,
        adult = adult,
        backdropPath = backdropPath,
        originalLanguage = originalLanguage,
        originalTitle = originalTitle,
        overview = overview,
        popularity = popularity,
        posterPath = posterPath,
        releaseDate = releaseDate,
        title = title,
        video = video,
        voteAverage = voteAverage,
        voteCount = voteCount
    )
}